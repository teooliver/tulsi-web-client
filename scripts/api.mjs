// Fetches the backend's OpenAPI spec and generates the Effect client from it.
//
//   node scripts/api.mjs spec       download the spec to api/openapi.json (backend must be running)
//   node scripts/api.mjs generate   regenerate src/api/generated.ts from api/openapi.json
//   node scripts/api.mjs check      fail if src/api/generated.ts is stale
//
// Before generating, every object schema without an explicit
// `additionalProperties` is closed (set to false). utoipa never emits it, and
// the generator would otherwise add a `[key: string]: Json` index signature to
// every type. Effect's Schema.Struct ignores unknown keys when decoding, so this
// is safe at runtime.

import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const SPEC_PATH = 'api/openapi.json'
const OUTPUT_PATH = 'src/api/generated.ts'
const CLIENT_NAME = 'TulsiApi'
const specUrl = `${process.env.API_URL ?? 'http://localhost:8080'}/api-docs/openapi.json`

const closeObjectSchemas = node => {
  if (Array.isArray(node)) {
    node.forEach(closeObjectSchemas)
    return
  }
  if (node === null || typeof node !== 'object') {
    return
  }
  const isObject =
    node.type === 'object' ||
    (Array.isArray(node.type) && node.type.includes('object'))
  if (isObject && node.properties && node.additionalProperties === undefined) {
    node.additionalProperties = false
  }
  Object.values(node).forEach(closeObjectSchemas)
}

const generate = () => {
  const spec = JSON.parse(readFileSync(SPEC_PATH, 'utf8'))
  closeObjectSchemas(spec)
  const dir = mkdtempSync(join(tmpdir(), 'tulsi-api-'))
  try {
    const closedSpecPath = join(dir, 'openapi.json')
    writeFileSync(closedSpecPath, JSON.stringify(spec))
    const header =
      '// GENERATED by `pnpm api:generate` from api/openapi.json. Do not edit.\n'
    return (
      header +
      execFileSync(
        'openapigen',
        ['-s', closedSpecPath, '-n', CLIENT_NAME, '-f', 'httpclient'],
        { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
      )
    )
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

const commands = {
  spec: async () => {
    const response = await fetch(specUrl)
    if (!response.ok) {
      throw new Error(`GET ${specUrl} failed with ${response.status}`)
    }
    const spec = await response.json()
    writeFileSync(SPEC_PATH, JSON.stringify(spec, null, 2) + '\n')
    console.log(`Wrote ${SPEC_PATH} from ${specUrl}`)
  },
  generate: () => {
    writeFileSync(OUTPUT_PATH, generate())
    console.log(`Wrote ${OUTPUT_PATH}`)
  },
  check: () => {
    if (readFileSync(OUTPUT_PATH, 'utf8') !== generate()) {
      console.error(`${OUTPUT_PATH} is stale. Run \`pnpm api:generate\`.`)
      process.exit(1)
    }
  },
}

const command = commands[process.argv[2]]
if (!command) {
  console.error('Usage: node scripts/api.mjs <spec|generate|check>')
  process.exit(1)
}
await command()
